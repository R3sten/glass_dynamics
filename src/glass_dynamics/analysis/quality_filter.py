"""
Experimental Quality Analysis and Outlier Filtering Module.

Identifies and removes glass-forming liquids whose raw experimental viscosity 
measurements exhibit severe noise, bifurcations, or poor adherence to the 
reference MYEGA equation (typically caused by database deduplication artifacts).
"""

import numpy as np
import pandas as pd
from typing import Tuple, Optional, Any
from glass_dynamics.core.logger import logger


def compute_myega_viscosity(
    T: np.ndarray, 
    log_inf: np.ndarray, 
    Tg: np.ndarray, 
    m: np.ndarray
) -> np.ndarray:
    """
    Calculates log10(Viscosity) using the vectorized MYEGA equation.

    Parameters
    ----------
    T : np.ndarray
        Experimental temperatures (K).
    log_inf : np.ndarray
        High-temperature viscosity limit.
    Tg : np.ndarray
        Glass transition temperature (K).
    m : np.ndarray
        Fragility index.

    Returns
    -------
    np.ndarray
        Calculated log10(Viscosity).
    """
    T = np.maximum(T, 1e-9)
    term1 = (12.0 - log_inf) * (Tg / T)
    term2 = np.exp((m / (12.0 - log_inf) - 1.0) * (Tg / T - 1.0))
    return log_inf + term1 * term2


def evaluate_experimental_fit_quality(
    viscosity_df: pd.DataFrame,
    y_df: pd.DataFrame,
    y_scaler: Optional[Any] = None
) -> pd.DataFrame:
    """
    Computes the intrinsic MYEGA fit error (MSE, RMSE, MAE, Max Error) for each 
    individual glass liquid by comparing its experimental points against the 
    curve generated by its reference MYEGA parameters.

    Parameters
    ----------
    viscosity_df : pd.DataFrame
        Raw experimental dataset containing 'ID', 'T', and 'log_visc'.
    y_df : pd.DataFrame
        Target DataFrame indexed by Glass ID containing the reference MYEGA 
        parameters (Tg, m, log_inf). Can be scaled or in physical units.
    y_scaler : Any, optional
        Fitted scaler used on y_df. If provided, transforms y_df back to 
        physical units prior to evaluating the MYEGA curve.

    Returns
    -------
    pd.DataFrame
        DataFrame indexed by Glass ID, sorted descending by 'myega_rmse' 
        (worst/noisiest liquids first), containing columns:
        ['n_points', 'myega_mse', 'myega_rmse', 'myega_mae', 'myega_max_err'].
    """
    target_cols = y_df.columns.tolist()
    tg_col = next(c for c in target_cols if 'Tg' in c)
    m_col = next(c for c in target_cols if 'm' in c)
    inf_col = next(c for c in target_cols if 'inf' in c.lower())

    # Convert reference parameters to physical units if a scaler is provided
    if y_scaler is not None:
        y_phys = pd.DataFrame(
            y_scaler.inverse_transform(y_df),
            index=y_df.index,
            columns=target_cols
        )
    else:
        y_phys = y_df.copy()

    # Filter experimental points matching the provided glass IDs
    valid_visc = viscosity_df[viscosity_df['ID'].isin(y_phys.index)].copy()
    merged = valid_visc.join(y_phys, on='ID', how='inner')

    # Calculate theoretical MYEGA viscosity and point-wise residuals
    merged['fitted_visc'] = compute_myega_viscosity(
        T=merged['T'].to_numpy(),
        log_inf=merged[inf_col].to_numpy(),
        Tg=merged[tg_col].to_numpy(),
        m=merged[m_col].to_numpy()
    )
    merged['abs_error'] = np.abs(merged['log_visc'] - merged['fitted_visc'])
    merged['sq_error'] = merged['abs_error'] ** 2

    # Aggregate error statistics per Glass ID
    grouped = merged.groupby('ID')
    quality_df = pd.DataFrame({
        'n_points': grouped['sq_error'].count(),
        'myega_mse': grouped['sq_error'].mean(),
        'myega_rmse': np.sqrt(grouped['sq_error'].mean()),
        'myega_mae': grouped['abs_error'].mean(),
        'myega_max_err': grouped['abs_error'].max()
    })

    # Ensure all IDs from y_df are present
    quality_df = quality_df.reindex(y_df.index)
    
    # Sort from worst fit (highest RMSE) to best fit
    quality_df = quality_df.sort_values(by='myega_rmse', ascending=False)

    logger.info(
        f"Evaluated experimental MYEGA fit quality for {len(quality_df)} liquids. "
        f"Median RMSE: {quality_df['myega_rmse'].median():.4f}, "
        f"Max RMSE: {quality_df['myega_rmse'].max():.4f}"
    )

    return quality_df


def filter_noisy_liquids(
    X: pd.DataFrame,
    y: pd.DataFrame,
    quality_df: pd.DataFrame,
    max_rmse: Optional[float] = None,
    drop_worst_pct: Optional[float] = None
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Filters out noisy glass-forming liquids from X and y based on their 
    intrinsic MYEGA fit RMSE.

    Parameters
    ----------
    X : pd.DataFrame
        Feature matrix indexed by Glass ID.
    y : pd.DataFrame
        Target matrix indexed by Glass ID.
    quality_df : pd.DataFrame
        Output of `evaluate_experimental_fit_quality` containing 'myega_rmse'.
    max_rmse : float, optional
        Absolute physical threshold for MYEGA RMSE (in log10 viscosity units).
        Liquids with myega_rmse > max_rmse are removed.
    drop_worst_pct : float, optional
        Percentage of worst liquids to drop (between 0 and 100, e.g., 5.0 drops 
        the worst 5% of liquids in the provided set). Ignored if max_rmse is set.

    Returns
    -------
    X_clean : pd.DataFrame
        Filtered feature matrix.
    y_clean : pd.DataFrame
        Filtered target matrix.
    dropped_info : pd.DataFrame
        Subset of quality_df corresponding to the removed outlier liquids.
    """
    if max_rmse is None and drop_worst_pct is None:
        raise ValueError("Specify either 'max_rmse' or 'drop_worst_pct' to filter liquids.")

    # Align quality metrics with the current subset (e.g., Train or Test)
    subset_quality = quality_df.loc[X.index].copy()

    if max_rmse is not None:
        threshold = float(max_rmse)
        mode_str = f"max_rmse={threshold:.4f}"
    else:
        if not (0.0 < drop_worst_pct < 100.0):
            raise ValueError("'drop_worst_pct' must be strictly between 0 and 100.")
        threshold = float(np.nanpercentile(subset_quality['myega_rmse'], 100.0 - drop_worst_pct))
        mode_str = f"drop_worst_pct={drop_worst_pct}% (computed threshold RMSE={threshold:.4f})"

    # Identify clean vs corrupted IDs
    keep_mask = subset_quality['myega_rmse'] <= threshold
    clean_ids = subset_quality.index[keep_mask]
    dropped_ids = subset_quality.index[~keep_mask]

    X_clean = X.loc[clean_ids].copy()
    y_clean = y.loc[clean_ids].copy()
    dropped_info = subset_quality.loc[dropped_ids].sort_values(by='myega_rmse', ascending=False)

    logger.info(
        f"Filtered noisy liquids [{mode_str}]: kept {len(clean_ids)}/{len(X)} "
        f"({len(dropped_ids)} noisy liquids removed)."
    )

    return X_clean, y_clean, dropped_info